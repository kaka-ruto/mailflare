import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test, { after } from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = mkdtempSync(join(tmpdir(), "mailflare-migrations-"));
after(() => rmSync(outDir, { recursive: true, force: true }));

// Tables the backup format deliberately leaves out, mirroring INTERNAL_TABLES in
// src/lib/backups/export.ts. `d1_migrations` is created by the Worker's own
// migration runner rather than a migration file, so it never appears below.
const INTERNAL_TABLES = ["d1_migrations", "jmap_mailbox_revisions"];

await build({
	stdin: {
		contents: `
			export * from "./src/lib/backups/table-groups";
			export { BACKUP_TABLES } from "./src/lib/backups/export";
		`,
		resolveDir: root,
		loader: "ts",
	},
	outfile: join(outDir, "backups.mjs"),
	bundle: true,
	platform: "node",
	format: "esm",
	target: "node22",
	logLevel: "silent",
	alias: { "@": join(root, "src") },
});

const { BACKUP_TABLE_GROUPS, BACKUP_TABLES } = await import(pathToFileURL(join(outDir, "backups.mjs")).href);

const migrationsDirectory = join(root, "drizzle", "migrations");
const migrationFiles = readdirSync(migrationsDirectory)
	.filter((name) => name.endsWith(".sql"))
	.sort();

/**
 * Tables that survive to the final schema, after replays every migration in
 * order and applies creates, drops and renames. Tables a later migration
 * removed or renamed away (message_bodies, agent_ai_usage) are gone from the
 * live database, so requiring backups to list them would be wrong.
 */
function survivingTables() {
	const alive = new Set();
	for (const name of [...migrationFiles].sort()) {
		const sql = readFileSync(join(migrationsDirectory, name), "utf8");
		for (const match of sql.matchAll(/^CREATE TABLE (?:IF NOT EXISTS )?`([a-z_]+)`/gm)) alive.add(match[1]);
		for (const match of sql.matchAll(/^DROP TABLE (?:IF EXISTS )?`([a-z_]+)`/gm)) alive.delete(match[1]);
		for (const match of sql.matchAll(/^ALTER TABLE `([a-z_]+)` RENAME TO `([a-z_]+)`/gm)) {
			if (alive.delete(match[1])) alive.add(match[2]);
		}
	}
	return alive;
}

const migratedTables = survivingTables();

test("every table the final schema contains is backed up or documented as internal", () => {
	const unlisted = [...migratedTables].filter((table) => !BACKUP_TABLES.includes(table) && !INTERNAL_TABLES.includes(table));
	assert.deepEqual(
		unlisted,
		[],
		`${unlisted.join(", ")} exist in the schema built by drizzle/migrations but are not in BACKUP_TABLES or INTERNAL_TABLES (src/lib/backups/export.ts). Backups would silently omit them.`,
	);
});

test("tables listed as internal are actually created by a migration", () => {
	const created = new Set();
	for (const name of migrationFiles) {
		for (const match of readFileSync(join(migrationsDirectory, name), "utf8").matchAll(/^CREATE TABLE (?:IF NOT EXISTS )?`([a-z_]+)`/gm)) {
			created.add(match[1]);
		}
	}
	// d1_migrations is created by the Worker's own runner (MIGRATION_TABLE_SQL in
	// src/lib/migrations/service.ts) rather than a migration file, so it has no
	// CREATE TABLE to find.
	const fromMigrations = INTERNAL_TABLES.filter((table) => table !== "d1_migrations");
	for (const table of fromMigrations) {
		assert.ok(created.has(table), `${table} is listed as internal but no migration creates it; remove it from INTERNAL_TABLES`);
	}
});

test("every backed-up table sits in exactly one group, and no group lists a table that is not backed up", () => {
	const grouped = BACKUP_TABLE_GROUPS.flatMap((group) => group.tables);
	const duplicates = grouped.filter((table, index) => grouped.indexOf(table) !== index);
	assert.deepEqual(duplicates, [], `${duplicates.join(", ")} appear in more than one backup table group`);

	const ungrouped = BACKUP_TABLES.filter((table) => !grouped.includes(table));
	assert.deepEqual(ungrouped, [], `${ungrouped.join(", ")} are in BACKUP_TABLES but no group selects them, so they are never backed up`);

	const unknown = grouped.filter((table) => !BACKUP_TABLES.includes(table));
	assert.deepEqual(unknown, [], `${unknown.join(", ")} are listed in a group but not in BACKUP_TABLES`);
});

test("the migration bundle the Worker ships matches the committed migrations exactly", async () => {
	const bundlePath = join(root, "src", "lib", "migrations", "bundle.json");
	if (!existsSync(bundlePath)) {
		// Generated by `npm run db:bundle`, which CI runs before the checks. Skipping
		// keeps the suite usable without a build step.
		return;
	}
	const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));
	const bundled = bundle.migrations.map((migration) => migration.name);

	const uncommitted = migrationFiles.filter((name) => !bundled.includes(name));
	assert.deepEqual(uncommitted, [], `${uncommitted.join(", ")} are committed but missing from the Worker's migration bundle, so the deployed Worker would never apply them. Run npm run db:bundle`);

	const stale = bundled.filter((name) => !migrationFiles.includes(name));
	assert.deepEqual(stale, [], `${stale.join(", ")} are in the bundle but no longer committed; the bundle is stale`);

	const empty = bundle.migrations.filter((migration) => !Array.isArray(migration.statements) || migration.statements.length === 0);
	assert.deepEqual(empty.map((migration) => migration.name), [], "these bundled migrations have no statements and would be recorded as applied without changing anything");
});
